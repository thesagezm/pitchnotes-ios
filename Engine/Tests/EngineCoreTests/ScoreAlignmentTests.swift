//
//     THE MEASURED NUMBERS ARE PINNED (the artifact-test precedent): a change
//     in what the engine MEASURES must be a visible, deliberate change.
//
//     HONESTY (AGENTS §11), stated here and in the queue row:
//       · The score fixture is DERIVED FROM THE SYNTHESIS TRUTH, so "the
