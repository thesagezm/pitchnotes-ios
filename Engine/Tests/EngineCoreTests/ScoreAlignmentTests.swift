    // MARK: - The frame budget (the binning path)

    func testLongAudioIsBinnedIntoTheFrameBudget() throws {
        // 2500 candidate frames (> the 2000-frame budget) of a simple
        // alternating two-pitch signal, against a 2-measure score of the same
        // two pitches. The alignment must succeed through the binning path —
        // finite confidence, a monotone bar map, and no memory blow-up.
        var frames: [[SalienceCandidate]] = []
        for index in 0..<2500 {
            let midi = index % 2 == 0 ? 60 : 64
            frames.append([SalienceCandidate(frameIndex: index,
                                             time: BasicPitchFrameClock.seconds(forFrame: index),
                                             midi: midi, salience: 0.9)])
        }
        let xml = """
        <score-partwise version="3.1">
          <part-list><score-part id="P1"><part-name>Bass</part-name></score-part></part-list>
          <part id="P1">
            <measure number="1">
              <attributes><divisions>4</divisions></attributes>
              <sound tempo="120"/>
              <note><pitch><step>C</step><octave>4</octave></pitch><duration>16</duration><voice>1</voice></note>
            </measure>
            <measure number="2">
              <note><pitch><step>E</step><octave>4</octave></pitch><duration>16</duration><voice>1</voice></note>
            </measure>
          </part>
        </score-partwise>
        """
        let score = try MusicXMLScoreParser.parse(data: Data(xml.utf8))
        let outcome = ScoreAligner.resolve(score: score, candidates: frames,
                                           detectedTracks: [:], audioDuration: 32.0)
        let alignment = try XCTUnwrap(outcome.alignment)
        XCTAssertTrue(alignment.confidence.isFinite)
        XCTAssertGreaterThan(alignment.confidence, 0.0)
        XCTAssertEqual(alignment.barMap.count, 2)
        for index in 1..<alignment.barMap.count {
            XCTAssertGreaterThanOrEqual(alignment.barMap[index].start_s,
                                        alignment.barMap[index - 1].end_s)
        }
        XCTAssertLessThanOrEqual(alignment.barMap.last!.end_s, 32.0,
                                 "the last bar end never exceeds the audio's duration")
    }
