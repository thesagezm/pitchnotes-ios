    /// THE MEASURED CONFIGURATION: the aligner's defaults are the prototype's
    /// (bandFraction 0.15, maxFrames 2000, the 0.70 adoption threshold).
    func testTheScoreFixtureDemonstratesTheAlignmentMechanism() throws {
        let artifact = try loadAssignmentArtifact()
        let testCase = try XCTUnwrap(artifact.cases.first { $0.name == "satb5_prog" })
        let parts = try testCase.parts_low_to_high.map { part in
            guard let parsed = Part(rawValue: part) else {
                throw NSError(domain: "test", code: 1,
                              userInfo: [NSLocalizedDescriptionKey: "unknown part \(part)"])
            }
            return parsed
        }
        let score = try loadScoreFixture()
        let tracks = detectedTracks(of: testCase, parts: parts)

        let outcome = ScoreAligner.resolve(score: score,
                                           candidates: candidates(of: testCase),
                                           detectedTracks: tracks,
                                           audioDuration: 8.0)

        // 1. THE ALIGNMENT EXISTS and is excellent.
        let alignment = try XCTUnwrap(outcome.alignment,
                                      "the committed score+audio must align")
        XCTAssertEqual(alignment.method, "DTW")
        XCTAssertEqual(alignment.confidence, 0.990145, accuracy: 1e-6,
                       "the MEASURED confidence (the prototype's)")
        XCTAssertGreaterThanOrEqual(alignment.confidence, 0.70,
                                    "D-41 §4's confidence gate")

        // 2. THE BAR MAP: 4 monotone entries; the MEASURED boundaries (the
        //    anchored warp's scale is 0.799299314 — the prototype's); the
        //    error against the truth's chord times is ≤ 50 ms (the AC), and
        //    the measured max is 7.0 ms.
        XCTAssertEqual(alignment.barMap.count, 4)
        let scale = 0.799299314
        XCTAssertEqual(alignment.barMap[0].start_s, 0.0, accuracy: 1e-6)
        XCTAssertEqual(alignment.barMap[0].end_s, scale * 2.5, accuracy: 1e-6)
        XCTAssertEqual(alignment.barMap[1].start_s, scale * 2.5, accuracy: 1e-6)
        XCTAssertEqual(alignment.barMap[1].end_s, scale * 5.0, accuracy: 1e-6)
        XCTAssertEqual(alignment.barMap[2].start_s, scale * 5.0, accuracy: 1e-6)
        XCTAssertEqual(alignment.barMap[2].end_s, scale * 7.5, accuracy: 1e-6)
        XCTAssertEqual(alignment.barMap[3].start_s, scale * 7.5, accuracy: 1e-6)
        XCTAssertEqual(alignment.barMap[3].end_s, scale * 10.0, accuracy: 1e-6)
        for index in 1..<alignment.barMap.count {
            XCTAssertGreaterThanOrEqual(alignment.barMap[index].start_s,
