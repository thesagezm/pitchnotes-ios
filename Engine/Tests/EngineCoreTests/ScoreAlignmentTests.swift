    func testTheCommittedScoreFixtureMatchesItsTruthTable() throws {
        // The score fixture is DERIVED from the synthesis truth (gen.py); the
        // parsed notes must be exactly the truth's 20 notes, at the score's
        // own 96 BPM tempo (2.5 s measures — BEFORE any alignment, C-13.1).
        let artifact = try loadAssignmentArtifact()
        let testCase = try XCTUnwrap(artifact.cases.first { $0.name == "satb5_prog" })
        let parts = testCase.parts_low_to_high
        let score = try loadScoreFixture()

        XCTAssertEqual(score.noteList.scoreNotes.count, 20)
        XCTAssertEqual(score.noteList.duration, 10.0, accuracy: 1e-9)
        XCTAssertEqual(score.noteList.measures, [1, 2, 3, 4])
        XCTAssertEqual(score.noteList.partIdentifiers, ["P1", "P2", "P3", "P4", "P5"])

        let expected = try truthChords(testCase) // sorted by part name
        for measure in 1...4 {
            let notesInMeasure = score.noteList.scoreNotes
                .filter { $0.measure == measure }
                .sorted { $0.part_id < $1.part_id }
            XCTAssertEqual(notesInMeasure.count, 5, "measure \(measure)")
            for (index, note) in notesInMeasure.enumerated() {
                let (partName, midi) = expected[measure - 1][index]
                // Pitch order: P1..P5 = BASS, BARITONE, BARITENOR, T2, T1.
                XCTAssertEqual(note.part_id, "P\(parts.firstIndex(of: partName)! + 1)")
                XCTAssertEqual(note.midi, midi, "\(partName) measure \(measure)")
                let measureStart = Double(measure - 1) * 2.5
                XCTAssertEqual(note.start_s, measureStart, accuracy: 1e-9)
                XCTAssertEqual(note.end_s, measureStart + 2.5, accuracy: 1e-9)
                XCTAssertEqual(note.voice, 1)
            }
        }
    }

    // MARK: - (2) The contract's JSON, exactly (D-52 §4)

    /// The PORTABLE exact-JSON pin: JSONEncoder's raw key order is a
    /// dictionary-iteration detail (it differs between Foundations — it is
    /// NOT contract surface), so the pin re-serialises with `.sortedKeys` and
    /// asserts the canonical string. Keys, values, nesting and the
    /// number formatting are all pinned; only the meaningless ordering is not.
    private func canonicalJSON(_ data: Data) throws -> String {
        let object = try JSONSerialization.jsonObject(with: data)
        let sorted = try JSONSerialization.data(withJSONObject: object, options: [.sortedKeys])
        return try XCTUnwrap(String(data: sorted, encoding: .utf8))
    }

    func testTheC131JSONIsExactlyTheContractShape() throws {
        let list = ScoreContract.NoteList(scoreNotes: [
            ScoreContract.Note(midi: 60, start_s: 0.0, end_s: 0.5,
                               measure: 1, part_id: "P1", voice: 1),
        ])
        let data = try JSONEncoder().encode(list)
        // D-52 §4: the engine's namespaced types emit the IDENTICAL JSON of
        // C-13.1 — key for key, value for value, pinned.
        XCTAssertEqual(try canonicalJSON(data),
                       #"{"contractVersion":"v1.1","scoreNotes":[{"end_s":0.5,"measure":1,"midi":60,"part_id":"P1","start_s":0,"voice":1}]}"#)
        // And it round-trips.
        let decoded = try JSONDecoder().decode(ScoreContract.NoteList.self, from: data)
        XCTAssertEqual(decoded, list)
    }

