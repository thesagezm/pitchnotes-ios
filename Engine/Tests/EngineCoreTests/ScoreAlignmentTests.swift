    func testScoreTimewiseIsRejectedWithAnHonestError() throws {
        let xml = """
        <score-timewise version="3.1">
          <measure number="1"><part id="P1"></part></measure>
        </score-timewise>
        """
        do {
            _ = try MusicXMLScoreParser.parse(data: Data(xml.utf8))
            XCTFail("a <score-timewise> document must be rejected (D-40 §2)")
        } catch let error as MusicXMLScoreError {
            guard case .unsupportedDocument(let reason) = error else {
                XCTFail("the error must be .unsupportedDocument, got \(error)")
                return
            }
            XCTAssertTrue(reason.contains("score-partwise"),
                          "the error must say what IS supported, got: \(reason)")
        }
    }

    func testAFileWithOnlyExcludedFeaturesYieldsAnEmptyScoreAndANotice() throws {
