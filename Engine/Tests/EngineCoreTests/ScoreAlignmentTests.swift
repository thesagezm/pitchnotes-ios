    func testTheC132AbsenceRulesAreTheContractAbsenceRules() throws {
        // No method ⇒ "unknown"; no barMap ⇒ []; no partMapping ⇒ nil (no
        // score note enters any part); a mapping value that is not a C-1
        // rawValue is dropped, never a decode error (D-47 §8).
        let json = #"{"contractVersion":"v1.1","alignment":{"confidence":0.5,"used":false,"partMapping":{"P1":"TUBA","P2":"BASS"}}}"#
        let file = try JSONDecoder().decode(ScoreContract.AlignmentFile.self, from: Data(json.utf8))
        XCTAssertEqual(file.alignment.methodName, "unknown")
        XCTAssertEqual(file.alignment.barMap, [])
        XCTAssertEqual(file.alignment.partMapping, ["P2": .bass])
        // The re-encoded file says exactly what survived: TUBA dropped, the
        // method absent, the (empty) bar map present.
        XCTAssertEqual(try canonicalJSON(JSONEncoder().encode(file)),
                       #"{"alignment":{"barMap":[],"confidence":0.5,"partMapping":{"P2":"BASS"},"used":false},"contractVersion":"v1.1"}"#)

        let bare = #"{"contractVersion":"v1.1","alignment":{"confidence":0.5,"used":false}}"#
        let bareFile = try JSONDecoder().decode(ScoreContract.AlignmentFile.self,
                                                from: Data(bare.utf8))
        XCTAssertNil(bareFile.alignment.partMapping)
        XCTAssertEqual(try canonicalJSON(JSONEncoder().encode(bareFile)),
                       #"{"alignment":{"barMap":[],"confidence":0.5,"used":false},"contractVersion":"v1.1"}"#)
    }

