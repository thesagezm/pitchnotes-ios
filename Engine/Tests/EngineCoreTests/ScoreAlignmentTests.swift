    func testARestAdvancesTheTimeline() throws {
        let xml = """
        <score-partwise version="3.1">
          <part-list><score-part id="P1"><part-name>One</part-name></score-part></part-list>
          <part id="P1">
            <measure number="1">
              <attributes><divisions>1</divisions></attributes>
              <note><rest/><duration>4</duration><voice>1</voice></note>
              <note><pitch><step>C</step><octave>4</octave></pitch><duration>4</duration><voice>1</voice></note>
            </measure>
          </part>
        </score-partwise>
        """
        let score = try MusicXMLScoreParser.parse(data: Data(xml.utf8))
        XCTAssertEqual(score.noteList.scoreNotes.count, 1)
        let note = try XCTUnwrap(score.noteList.scoreNotes.first)
        // The rest (4 divisions at 120 BPM's default 0.5 s/quarter) advanced
        // the cursor to 2.0 s before the note began.
        XCTAssertEqual(note.start_s, 2.0, accuracy: 1e-12)
        XCTAssertEqual(note.end_s, 4.0, accuracy: 1e-12)
    }

    func testAMidPartDivisionsChangeIsHonoured() throws {
        let xml = """
        <score-partwise version="3.1">
          <part-list><score-part id="P1"><part-name>One</part-name></score-part></part-list>
          <part id="P1">
            <measure number="1">
              <attributes><divisions>4</divisions></attributes>
