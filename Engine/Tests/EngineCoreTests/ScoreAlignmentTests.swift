    /// The heuristic detected tracks, from the artifact's per-part note events.
    private func detectedTracks(of testCase: Artifact.Case, parts: [Part]) -> [Part: NoteTrack] {
        var tracks: [Part: NoteTrack] = [:]
        for part in parts {
            let notes = (testCase.notes[part.rawValue] ?? []).map {
                EngineCore.Note(start_s: $0.start_s, end_s: $0.end_s, midi: $0.midi,
                                cents_ref: 0, confidence: $0.confidence,
                                salience: $0.salience)
            }
            tracks[part] = NoteTrack(contractVersion: NoteTrack.contractVersionV11,
                                     part: part, notes: notes)
        }
        return tracks
    }

    /// The frame-accuracy counter (the prototype's exact metric): a frame is
    /// correct when the notes covering its time name the same (partIndex,
    /// midi) pairs as the truth frame.
    private func frameAccuracy(aligned: [ScoreContract.AlignedNote],
                               parts: [Part], truth: [[[Int]]],
                               frameCount: Int) -> Int {
        let partIndex = Dictionary(uniqueKeysWithValues: parts.enumerated().map { ($1, $0) })
        var hits = 0
        for frame in 0..<frameCount {
            let time = BasicPitchFrameClock.seconds(forFrame: frame)
            let predicted = aligned
                .filter { $0.part != nil && $0.alignedStart_s <= time && time < $0.alignedEnd_s }
                .map { [partIndex[$0.part!]!, $0.midi] }
                .sorted { $0.lexicographicallyPrecedes($1) }
            let expected = truth[frame].map { [$0[0], $0[1]] }
                .sorted { $0.lexicographicallyPrecedes($1) }
            if predicted == expected { hits += 1 }
        }
        return hits
    }

    /// The heuristic baseline: the artifact's own per-frame assignment.
    private func heuristicFrameAccuracy(_ testCase: Artifact.Case) -> Int {
        var hits = 0
        for (frame, assignment) in testCase.assignment.enumerated() {
            let predicted = assignment.pitches.map { [$0[0], $0[1]] }
                .sorted { $0.lexicographicallyPrecedes($1) }
            let expected = testCase.truth_frames[frame].map { [$0[0], $0[1]] }
                .sorted { $0.lexicographicallyPrecedes($1) }
            if predicted == expected { hits += 1 }
        }
        return hits
    }

    /// The 5-voice truth of the satb5_prog case, in the artifact's PITCH
    /// order (which is exactly the score's P1…P5 order).
    private func truthChords(_ testCase: Artifact.Case) throws -> [[(String, Int)]] {
        try testCase.truth_chords.map { chord in
            try testCase.parts_low_to_high.map { part -> (String, Int) in
                guard let midi = chord.pitches[part] else {
                    throw NSError(domain: "test", code: 1,
                                  userInfo: [NSLocalizedDescriptionKey: "no pitch for \(part)"])
                }
                return (part, midi)
            }
        }
    }

    /// The MusicXML of the SAME truth at ANOTHER tempo (the adopted branch's
    /// variant — built here from the artifact's truth, never committed).
    private func scoreXML(chords: [[(String, Int)]], parts: [String], tempo: Int) -> String {
        let labels: [String: String] = ["BASS": "Bass", "BARITONE": "Baritone",
                                        "BARITENOR": "Baritenor", "T2": "Tenor 2", "T1": "Tenor 1"]
        let steps = [0: "C", 2: "D", 4: "E", 5: "F", 7: "G", 9: "A", 11: "B"]
        var xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<score-partwise version=\"3.1\">\n  <part-list>"
        for (index, part) in parts.enumerated() {
            xml += "\n    <score-part id=\"P\(index + 1)\"><part-name>\(labels[part]!)</part-name></score-part>"
        }
        xml += "\n  </part-list>"
        for (index, part) in parts.enumerated() {
            xml += "\n  <part id=\"P\(index + 1)\">"
            for (measureIndex, chord) in chords.enumerated() {
                let midi = chord.first { $0.0 == part }!.1
                let step = steps[midi % 12]!
                let octave = midi / 12 - 1
                xml += "\n    <measure number=\"\(measureIndex + 1)\">"
                if measureIndex == 0 {
                    xml += "\n      <attributes><divisions>4</divisions></attributes>"
                    xml += "\n      <sound tempo=\"\(tempo)\"/>"
                }
                xml += "\n      <note><pitch><step>\(step)</step><octave>\(octave)</octave></pitch>"
                xml += "<duration>16</duration><voice>1</voice></note>\n    </measure>"
            }
            xml += "\n  </part>"
        }
        xml += "\n</score-partwise>\n"
        return xml
    }

