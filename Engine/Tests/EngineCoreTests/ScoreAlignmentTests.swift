                XCTAssertNil(note.assignmentBand,
                             "\(part.rawValue): the score is not the assignment")
            }
        }

        // 7. THE BUNDLE'S OWN TRACKS ARE UNTOUCHED: the heuristic tracks the
        //    caller passed in are exactly what it gets back.
        for part in parts {
            XCTAssertEqual(tracks[part]?.notes.count,
                           testCase.notes[part.rawValue]?.count,
                           "\(part.rawValue): the heuristic track was never mutated")
        }

        // 8. DETERMINISM: the same inputs, the same outcome, bit for bit.
        let second = ScoreAligner.resolve(score: score,
                                          candidates: candidates(of: testCase),
                                          detectedTracks: tracks,
                                          audioDuration: 8.0)
        XCTAssertEqual(second, outcome)
    }

    /// THE ADOPTED BRANCH of D-47 §9's strict rule, on the SAME truth at a
