    // MARK: - The placement rule (mirrors Jess's `ScoreReview.align`)

    func testThePlacementRuleMirrorsScoreReviewAlign() throws {
        // A 2-measure score: measure 1 has TWO notes (scaled onto the bar's
        // audio span); measure 2 has ONE note (keeps its own duration); part
        // P2 is UNMAPPED (placed in time, entering no part's track); measure
        // 3 is not covered by the bar map (its notes are skipped).
        func note(_ midi: Int, _ start: Double, _ end: Double, _ measure: Int,
                  _ partID: String) -> ScoreContract.Note {
            ScoreContract.Note(midi: midi, start_s: start, end_s: end,
                               measure: measure, part_id: partID, voice: 1)
        }
        let scoreNotes = [
            note(60, 0.0, 1.0, 1, "P1"),
            note(64, 1.0, 2.0, 1, "P1"),
            note(55, 2.0, 4.0, 2, "P1"),   // a single note, 2.0 s long
            note(48, 0.0, 2.0, 1, "P2"),   // unmapped part
            note(53, 4.0, 6.0, 3, "P1"),   // measure 3: not in the bar map
        ]
        let parsed = ParsedMusicXMLScore(
            noteList: ScoreContract.NoteList(scoreNotes: scoreNotes),
            partLabels: ["P1": "Bass", "P2": "Mystery"],
            tempoBPM: 120, divisionsPerQuarter: 4, notices: [])
        let barMap = [
            ScoreContract.BarMapEntry(measure: 1, start_s: 0.0, end_s: 3.0),
            ScoreContract.BarMapEntry(measure: 2, start_s: 3.0, end_s: 5.0),
        ]

        // Direct placement (the aligner's internal rule, which mirrors the
        // consumer's).
        let aligned = ScoreAligner.alignedNotes(
            score: parsed, barMap: barMap, mapping: ["P1": .bass])

        XCTAssertEqual(aligned.count, 4, "measure 3's note is skipped")
        // Measure 1, note 1: [0,1) scaled by audioSpan/scoreSpan = 3.0/2.0.
        XCTAssertEqual(aligned[0].alignedStart_s, 0.0, accuracy: 1e-12)
        XCTAssertEqual(aligned[0].alignedEnd_s, 1.5, accuracy: 1e-12)
        XCTAssertEqual(aligned[0].part, .bass)
        // Measure 1, note 2: [1,2) → [1.5, 3.0).
        XCTAssertEqual(aligned[1].alignedStart_s, 1.5, accuracy: 1e-12)
        XCTAssertEqual(aligned[1].alignedEnd_s, 3.0, accuracy: 1e-12)
        // Measure 2's single note keeps its own duration: [3,5) → [3,5).
        XCTAssertEqual(aligned[2].alignedStart_s, 3.0, accuracy: 1e-12)
        XCTAssertEqual(aligned[2].alignedEnd_s, 5.0, accuracy: 1e-12)
        // The unmapped part: placed IN TIME, part == nil.
        XCTAssertEqual(aligned[3].part, nil)
        XCTAssertEqual(aligned[3].alignedStart_s, 0.0, accuracy: 1e-12)
        XCTAssertEqual(aligned[3].alignedEnd_s, 3.0, accuracy: 1e-12)
        // And through resolve(): the unmapped note enters NO part's track.
        let candidates: [[SalienceCandidate]] = (0..<400).map { index in
            [SalienceCandidate(frameIndex: index,
                               time: BasicPitchFrameClock.seconds(forFrame: index),
                               midi: index % 2 == 0 ? 60 : 55,
                               salience: 0.9)]
        }
        let detected: [Part: NoteTrack] = [
            .bass: NoteTrack(part: .bass, notes: [
                EngineCore.Note(start_s: 0.0, end_s: 3.0, midi: 60, confidence: 0.9),
            ]),
        ]
        let outcome = ScoreAligner.resolve(score: parsed, candidates: candidates,
                                           detectedTracks: detected,
                                           audioDuration: 8.0)
        XCTAssertEqual(outcome.scoreInformedTracks.count, 1)
        XCTAssertEqual(outcome.scoreInformedTracks[.bass]?.notes.count, 4,
                       "through resolve() the bar map covers the score's own measures 1…3 (the DIRECT call above showed the skip when the map does not); the unmapped P2 note is in NO track")
        XCTAssertEqual(outcome.partMapping, ["P1": .bass],
                       "the unresolved 'Mystery' label stays unmapped")
    }

